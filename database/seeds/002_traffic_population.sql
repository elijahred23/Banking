SELECT NEWID(), c.Id, p.AccountNumber, p.OpeningBalance, 0, 0, 0, 0, 0, N'Open'
FROM @Profiles p JOIN dbo.Banks b ON b.RoutingNumber = p.Routing
CROSS APPLY (SELECT TOP (1) Id FROM dbo.Customers WHERE BankId = b.Id AND Name = p.Name ORDER BY Id) c
WHERE NOT EXISTS (SELECT 1 FROM dbo.Accounts a WITH (UPDLOCK, HOLDLOCK) WHERE a.AccountNumber = p.AccountNumber);
